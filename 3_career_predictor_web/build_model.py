"""Train the career classifier and export it for the standalone quiz."""

import json
from pathlib import Path

import pandas as pd
from sklearn.metrics import accuracy_score
from sklearn.model_selection import train_test_split
from sklearn.tree import DecisionTreeClassifier


ROOT = Path(__file__).resolve().parent
DATA_FILE = ROOT / "career_data.csv"
OUTPUT_FILE = ROOT / "model.js"
PROFILES = ["Tech", "Business", "Creative", "Social"]
QUESTIONS = [
    {
        "column": "tech_score",
        "statement": "I enjoy playing around with apps, coding, or figuring out how gadgets work.",
    },
    {
        "column": "logic_score",
        "statement": "I like solving puzzles, brain teasers, or working with numbers and charts.",
    },
    {
        "column": "leader_score",
        "statement": "I feel comfortable taking charge of group projects or planning events.",
    },
    {
        "column": "speech_score",
        "statement": "I am good at presenting my ideas clearly or persuading people to agree with me.",
    },
    {
        "column": "art_score",
        "statement": "I love drawing, designing layouts, making music, or editing videos.",
    },
    {
        "column": "writing_score",
        "statement": "I enjoy writing essays, creating stories, or blogging about things I like.",
    },
    {
        "column": "help_score",
        "statement": "I get a lot of satisfaction from teaching, coaching, or volunteering to help people.",
    },
    {
        "column": "team_score",
        "statement": "I prefer working in a team with friends over doing a project completely alone.",
    },
    {
        "column": "organize_score",
        "statement": "I like keeping my schedule, school notes, or bedroom clean and organized.",
    },
    {
        "column": "risk_score",
        "statement": "I like trying new things and starting my own projects, even if I might fail.",
    },
]
FEATURE_COLUMNS = [question["column"] for question in QUESTIONS]


def js_literal(value):
    """Serialize Python data as a JavaScript literal."""
    return json.dumps(value, ensure_ascii=False, separators=(",", ":"))


def main():
    data = pd.read_csv(DATA_FILE)
    x_train, x_test, y_train, y_test = train_test_split(
        data[FEATURE_COLUMNS],
        data["career_category"],
        test_size=0.25,
        random_state=42,
        stratify=data["career_category"],
    )
    model = DecisionTreeClassifier(
        max_depth=4,
        min_samples_leaf=2,
        random_state=42,
    )
    model.fit(x_train, y_train)
    accuracy = float(accuracy_score(y_test, model.predict(x_test)))

    tree = model.tree_
    classes = [str(profile) for profile in model.classes_]
    class_counts = []
    for node in range(tree.node_count):
        values = tree.value[node][0]
        counts = values * tree.weighted_n_node_samples[node]
        class_counts.append([int(round(float(count))) for count in counts])

    tree_data = {
        "classes": classes,
        "children_left": tree.children_left.tolist(),
        "children_right": tree.children_right.tolist(),
        "feature": tree.feature.tolist(),
        "threshold": [
            float(threshold) if tree.children_left[node] != -1 else 0.0
            for node, threshold in enumerate(tree.threshold)
        ],
        "class_counts": class_counts,
    }
    source = "\n".join(
        [
            "// Generated by build_model.py. Re-run when career_data.csv changes.",
            f"const QUESTIONS = {js_literal(QUESTIONS)};",
            f"const PROFILES = {js_literal(PROFILES)};",
            f"const TEST_ACCURACY = {accuracy!r};",
            f"const TREE = {js_literal(tree_data)};",
            "",
        ]
    )
    OUTPUT_FILE.write_text(source, encoding="utf-8")
    print(f"Test accuracy: {accuracy:.0%}")
    print(f"Wrote {OUTPUT_FILE.name} ({tree.node_count} tree nodes).")


if __name__ == "__main__":
    main()
